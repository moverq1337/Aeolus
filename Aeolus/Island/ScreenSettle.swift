import Foundation

/// Схождение геометрии экрана — тот же приём, что и `NowPlayingCoalescer`
/// для рваных медиа-источников, только источник здесь AppKit.
///
/// `didChangeScreenParameters` прилетает пачкой и приезжает раньше правды:
/// в момент нотификации `NSScreen` ещё отдаёт старую геометрию, а на смене
/// режима встроенный экран умеет на долю секунды вовсе пропасть из
/// `NSScreen.screens`. Одного замера мало: посчитали один раз, получили nil —
/// и остров исчез до следующей перенастройки монитора (это и есть баг
/// «сменил разрешение — островок сломался»).
///
/// Поэтому: замер сразу, затем перепроверки по затухающему графику. Задача
/// живёт только внутри окна схождения — инвариант «ноль таймеров в простое»
/// (спека §6.7) цел, ровно как у коалесера.
enum ScreenSettle {
    /// Задержки перепроверки от момента события. Ранние ловят быстрый переход
    /// между масштабами, поздние — медленный: пробуждение, приход внешнего
    /// монитора, возврат из клемшелла.
    static let probeDelays: [Duration] = [
        .milliseconds(150),
        .milliseconds(400),
        .milliseconds(800),
        .milliseconds(1500),
        .milliseconds(2500),
        .milliseconds(4000),
    ]

    enum Step: Equatable {
        /// Геометрия та же — окно не трогаем: пересборка рвёт SwiftUI-дерево,
        /// и остров моргает на каждой из пачки нотификаций.
        case keep
        /// Геометрия другая (или экран пропал/появился) — пересобрать окно.
        case rebuild
    }

    static func step(current: NotchMetrics?, fresh: NotchMetrics?) -> Step {
        current == fresh ? .keep : .rebuild
    }
}
